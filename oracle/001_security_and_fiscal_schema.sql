CREATE OR REPLACE FUNCTION onyx_can_post_date(
  p_user_id     IN NUMBER,
  p_company_id  IN NUMBER,
  p_post_date   IN DATE
) RETURN NUMBER IS
  v_business_date DATE;
  v_lock_date DATE;
  v_allow_backdate NUMBER;
  v_backdate_limit NUMBER;
  v_allow_future NUMBER;
  v_has_perm NUMBER;
BEGIN
  SELECT current_business_date, period_lock_date, allow_backdate_flag,
         backdate_days_limit, allow_future_date_flag
    INTO v_business_date, v_lock_date, v_allow_backdate,
         v_backdate_limit, v_allow_future
    FROM onyx_accounting_control
   WHERE company_id = p_company_id;

  SELECT COUNT(*) INTO v_has_perm
    FROM onyx_user_role ur
    JOIN onyx_role_permission rp ON rp.role_id = ur.role_id
    JOIN onyx_permission p ON p.permission_id = rp.permission_id
   WHERE ur.user_id = p_user_id AND p.permission_code = 'BACKDATE_POSTING';

  IF v_lock_date IS NOT NULL AND TRUNC(p_post_date) <= TRUNC(v_lock_date) THEN
    RETURN 0;
  ELSIF TRUNC(p_post_date) < TRUNC(v_business_date) THEN
    IF v_allow_backdate = 1 AND v_has_perm > 0
       AND TRUNC(v_business_date) - TRUNC(p_post_date) <= v_backdate_limit THEN
      RETURN 1;
    END IF;
    RETURN 0;
  ELSIF TRUNC(p_post_date) > TRUNC(v_business_date) THEN
    RETURN CASE WHEN v_allow_future = 1 THEN 1 ELSE 0 END;
  END IF;
  RETURN 1;
EXCEPTION
  WHEN NO_DATA_FOUND THEN RETURN 0;
END;
/


-- سجل تدقيق عام للعمليات الحساسة، منفصل عن سجل محاولات الدخول.
CREATE TABLE onyx_audit_log (
  audit_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id           NUMBER REFERENCES onyx_user(user_id),
  company_id        NUMBER REFERENCES onyx_company(company_id),
  branch_id         NUMBER REFERENCES onyx_branch(branch_id),
  fiscal_year_id    NUMBER REFERENCES onyx_fiscal_year(fiscal_year_id),
  action_code       VARCHAR2(80) NOT NULL,
  entity_type       VARCHAR2(80) NOT NULL,
  entity_id         VARCHAR2(80),
  before_value      CLOB,
  after_value       CLOB,
  reason            VARCHAR2(500),
  terminal_name     VARCHAR2(255),
  created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_onyx_audit_scope ON onyx_audit_log(company_id, branch_id, fiscal_year_id, created_at);
CREATE INDEX ix_onyx_audit_action ON onyx_audit_log(action_code, created_at);
COMMIT;
