CREATE TABLE onyx_company (
  company_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_code      VARCHAR2(30) NOT NULL UNIQUE,
  company_name_ar   VARCHAR2(200) NOT NULL,
  company_name_en   VARCHAR2(200),
  base_currency     VARCHAR2(3) DEFAULT 'SAR' NOT NULL,
  active_flag       NUMBER(1) DEFAULT 1 NOT NULL,
  created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE onyx_branch (
  branch_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id        NUMBER NOT NULL REFERENCES onyx_company(company_id),
  branch_code       VARCHAR2(30) NOT NULL,
  branch_name_ar    VARCHAR2(200) NOT NULL,
  branch_name_en    VARCHAR2(200),
  active_flag       NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT uq_onyx_branch UNIQUE (company_id, branch_code)
);

CREATE TABLE onyx_fiscal_year (
  fiscal_year_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id        NUMBER NOT NULL REFERENCES onyx_company(company_id),
  fiscal_year       NUMBER(4) NOT NULL,
  start_date        DATE NOT NULL,
  end_date          DATE NOT NULL,
  status_code       VARCHAR2(12) DEFAULT 'OPEN' NOT NULL,
  CONSTRAINT ck_onyx_fy_dates CHECK (end_date >= start_date),
  CONSTRAINT ck_onyx_fy_status CHECK (status_code IN ('OPEN','CLOSED','LOCKED')),
  CONSTRAINT uq_onyx_fy UNIQUE (company_id, fiscal_year)
);

CREATE TABLE onyx_user (
  user_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username          VARCHAR2(80) NOT NULL UNIQUE,
  display_name_ar   VARCHAR2(200) NOT NULL,
  password_hash     VARCHAR2(255) NOT NULL,
  language_code     VARCHAR2(10) DEFAULT 'ar' NOT NULL,
  active_flag       NUMBER(1) DEFAULT 1 NOT NULL,
  locked_until      TIMESTAMP,
  failed_attempts   NUMBER DEFAULT 0 NOT NULL,
  last_login_at     TIMESTAMP,
  created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE onyx_role (
  role_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_code         VARCHAR2(50) NOT NULL UNIQUE,
  role_name_ar      VARCHAR2(150) NOT NULL,
  active_flag       NUMBER(1) DEFAULT 1 NOT NULL
);

CREATE TABLE onyx_permission (
  permission_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  permission_code   VARCHAR2(80) NOT NULL UNIQUE,
  permission_name_ar VARCHAR2(200) NOT NULL
);

CREATE TABLE onyx_user_role (
  user_id           NUMBER NOT NULL REFERENCES onyx_user(user_id),
  role_id           NUMBER NOT NULL REFERENCES onyx_role(role_id),
  CONSTRAINT pk_onyx_user_role PRIMARY KEY (user_id, role_id)
);

CREATE TABLE onyx_role_permission (
  role_id           NUMBER NOT NULL REFERENCES onyx_role(role_id),
  permission_id     NUMBER NOT NULL REFERENCES onyx_permission(permission_id),
  CONSTRAINT pk_onyx_role_perm PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE onyx_user_scope (
  user_id           NUMBER NOT NULL REFERENCES onyx_user(user_id),
  company_id        NUMBER NOT NULL REFERENCES onyx_company(company_id),
  branch_id         NUMBER NOT NULL REFERENCES onyx_branch(branch_id),
  default_year_id   NUMBER REFERENCES onyx_fiscal_year(fiscal_year_id),
  CONSTRAINT pk_onyx_user_scope PRIMARY KEY (user_id, company_id, branch_id)
);

CREATE TABLE onyx_login_history (
  login_history_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id           NUMBER REFERENCES onyx_user(user_id),
  username_entered  VARCHAR2(80) NOT NULL,
  company_id        NUMBER REFERENCES onyx_company(company_id),
  branch_id         NUMBER REFERENCES onyx_branch(branch_id),
  fiscal_year_id    NUMBER REFERENCES onyx_fiscal_year(fiscal_year_id),
  language_code     VARCHAR2(10),
  terminal_name     VARCHAR2(255),
  login_type        VARCHAR2(20) NOT NULL,
  failure_reason    VARCHAR2(200),
  login_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  logout_at         TIMESTAMP
);

