function Quote-Sql([AllowNull()][string]$Value) {
  if ($null -eq $Value) { return 'NULL' }
  return "'" + $Value.Replace("'", "''") + "'"
}
function Date-Literal([datetime]$Value) { return "#$($Value.ToString('yyyy-MM-dd HH:mm:ss'))#" }

