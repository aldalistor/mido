    $catalog = New-Object -ComObject ADOX.Catalog
    $candidateString = "Provider=$candidate;Data Source=$Output;Jet OLEDB:Engine Type=6;"
    $catalog.Create($candidateString)
    $connectionString = $candidateString
    break
  } catch {
    if ($catalog) { [Runtime.InteropServices.Marshal]::ReleaseComObject($catalog) | Out-Null; $catalog = $null }
  }
}
